package ConditionlaSt;

public class IfElseIfEx {
	public static void main(String[] args) {
		
		int marks = 75;

		if (marks >= 90) {
		    System.out.println("A+");
		} 
		else if (marks >= 75) {
		    System.out.println("A");
		} 
		else if (marks >= 50) {
		    System.out.println("B");
		} 
		else {
		    System.out.println("Fail");
		}

	}

}
